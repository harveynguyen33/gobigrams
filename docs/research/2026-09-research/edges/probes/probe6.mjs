import {getSmoothStepPath, Position} from '@xyflow/react';
console.log('Position values:', JSON.stringify(Position));
const base = {sourceX: 100, sourceY: 300, targetX: 600, targetY: 300, sourcePosition: Position.Right, targetPosition: Position.Left, borderRadius: 12};
const withUndef = getSmoothStepPath({...base, stepPosition: undefined});
const omitted = getSmoothStepPath({...base});
const half = getSmoothStepPath({...base, stepPosition: 0.5});
console.log('explicit undefined === omitted :', withUndef[0] === omitted[0]);
console.log('explicit undefined === 0.5     :', withUndef[0] === half[0]);
console.log('undefined path:', withUndef[0]);
const zeroAndOne = [0, 1].map(p => getSmoothStepPath({...base, stepPosition: p})[0]);
console.log('0 vs 1 differ:', zeroAndOne[0] !== zeroAndOne[1]);
const rr = {sourceX: 100, sourceY: 300, targetX: 600, targetY: 300, sourcePosition: Position.Right, targetPosition: Position.Right};
const rrPaths = [0, 1].map(p => getSmoothStepPath({...rr, stepPosition: p})[0]);
console.log('R->R 0 vs 1 differ:', rrPaths[0] !== rrPaths[1]);
