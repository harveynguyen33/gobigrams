if (COMPONENTS.length !== ICON_NAMES.length) {
  throw new Error(
    `lucideIcons: ${COMPONENTS.length} components vs ${ICON_NAMES.length} names in src/gobi/iconNames.ts — the two lists must be edited together (aligned, alphabetical)`);
}

/** kebab-case icon name -> component. */
export const ICONS: Record<string, LucideIcon> = Object.fromEntries(
  ICON_NAMES.map((name, i) => [name, COMPONENTS[i]!]));

/** All pickable icon names, alphabetical — the ONE list, owned by
 *  src/gobi/iconNames.ts (re-exported so existing importers are unchanged). */
export {ICON_NAMES};

/** Resolve a stored icon value: a lucide component, or null when it is a raw glyph. */
export function lucideByName(name?: string | null): LucideIcon | null {
  if (!name) return null;
  return ICONS[name] ?? null;
}

/** Human label for a picker entry: "arrow-right-to-line" → "Arrow right to line". */
export function iconLabel(name: string): string {
  const s = name.replace(/-/g, ' ');
  return s.charAt(0).toUpperCase() + s.slice(1);
}
